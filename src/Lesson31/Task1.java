package Lesson31;

public class Task1 {
    public static void main(String[] args) {
        int a = 10;
        Integer integerA = a;

        System.out.println("int: " + a);
        System.out.println("Integer: " + integerA);

        double d = 15.5;
        Double doubleD = d;

        char c = 'A';
        Character characterC = c;

        boolean b = true;
        Boolean booleanB = b;

        System.out.println("Double: " + doubleD);
        System.out.println("Character: " + characterC);
        System.out.println("Boolean: " + booleanB);
    }
}